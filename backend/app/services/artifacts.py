class CreateArtifactRequest(BaseModel):
    title: str = Field(..., description="Title of the artifact")
    artifact_type: str = Field(..., description="'html', 'markdown', 'experiment', or 'brief'")
    content: Optional[str] = Field(None, description="Pre-composed content, or leave empty to generate")
    prompt: Optional[str] = Field(None, description="Prompt to generate artifact content if content is omitted")
    conversation_id: Optional[str] = None
    is_evidence_grounded: bool = True
    provider: Optional[str] = None


class ArtifactResponse(BaseModel):
    id: str
    conversation_id: Optional[str]
    title: str
    artifact_type: str
    content: str
    is_evidence_grounded: bool
    created_at: str
    metadata: Dict[str, Any]


def sanitize_html(html_content: str) -> str:
    """
    Sanitizes untrusted HTML content generated by language models.
    Guards against XSS vectors, external network leaks, cookie stealing,
    and localStorage manipulation.
    """
    if not html_content:
        return ""

    sanitized = html_content

    # Disallow script tags that access sensitive window/storage properties
    forbidden_patterns = [
        r"(?i)<script[^>]*>.*?window\.localStorage.*?</script>",
        r"(?i)<script[^>]*>.*?window\.sessionStorage.*?</script>",
        r"(?i)<script[^>]*>.*?document\.cookie.*?</script>",
        r"(?i)javascript:\s*",
        r"(?i)data:\s*text/html",
        r"(?i)document\.location",
        r"(?i)window\.location",
    ]

    for pat in forbidden_patterns:
        sanitized = re.sub(pat, "/* blocked_by_security_policy */", sanitized, flags=re.DOTALL)

    # Disallow dangerous nested iframes or objects
    sanitized = re.sub(r"(?i)<iframe[^>]*>.*?</iframe>", "<!-- nested iframe blocked -->", sanitized, flags=re.DOTALL)
    sanitized = re.sub(r"(?i)<object[^>]*>.*?</object>", "<!-- object blocked -->", sanitized, flags=re.DOTALL)
    sanitized = re.sub(r"(?i)<embed[^>]*>", "<!-- embed blocked -->", sanitized)

    # Strip dangerous event handlers like onload, onerror, onmouseover in raw tags
    sanitized = re.sub(r'(?i)\son\w+\s*=\s*["\'][^"\']*["\']', "", sanitized)

    return sanitized


async def create_or_generate_artifact(
    db: Session,
    request: CreateArtifactRequest,
) -> ArtifactResponse:
    """
    Creates a new artifact, either from supplied content or by generating it
    from retrieved evidence using the configured model provider.
    """
    title = request.title.strip()
    artifact_type = request.artifact_type.lower()
    content = request.content
    is_grounded = request.is_evidence_grounded

    if not content:
        # Generate artifact using model and retrieved evidence
        evidence_chunks = search_transcripts(db=db, query=request.prompt or title, limit=4)
        evidence_text = "\n\n".join([f"[{c.title}]: {c.excerpt}" for c in evidence_chunks]) if evidence_chunks else ""

        system_prompt = (
            f"You are a world-class growth designer and product engineer. "
            f"Generate a professional, fully-realized {artifact_type.upper()} deliverable.\n"
        )
        if evidence_text and is_grounded:
            system_prompt += (
                f"Ground the content strictly in these Lenny podcast/newsletter insights:\n"
                f"{evidence_text}\n"
            )
        else:
            system_prompt += "Create a high-fidelity template based on best product growth practices.\n"

        if artifact_type == "html":
            system_prompt += (
                "Return ONLY valid, modern, self-contained HTML and CSS code within a single complete document. "
                "Include clean CSS styles, responsive layout, clear typography, and professional color palette. "
                "Do NOT include markdown backticks around the HTML."
            )
        else:
            system_prompt += "Return clean, structured markdown with clear headings, tables, and bullet points."

        user_prompt = request.prompt or f"Create a {artifact_type} deliverable for: {title}"
        provider = router.get_provider(request.provider)
        logger.info(f"Generating {artifact_type} artifact with {provider.provider_name}")

        model_resp = await provider.complete(
            messages=[{"role": "user", "content": user_prompt}],
            system=system_prompt,
            temperature=0.3,
            max_tokens=2500,
        )
        content = model_resp.content.strip()

        # Clean backticks if model wrapped HTML in ```html ... ```
        if artifact_type == "html":
            if content.startswith("```"):
                content = re.sub(r"^```(?:html)?\s*", "", content)
                content = re.sub(r"\s*```$", "", content)

    # Sanitize if HTML
    if artifact_type == "html":
        content = sanitize_html(content)

    artifact_record = Artifact(
        conversation_id=request.conversation_id,
        title=title,
        artifact_type=artifact_type,
        content=content,
        is_evidence_grounded=is_grounded,
        artifact_metadata={"generated": True, "type": artifact_type},
    )
    db.add(artifact_record)
    db.commit()

    return ArtifactResponse(
        id=artifact_record.id,
        conversation_id=artifact_record.conversation_id,
        title=artifact_record.title,
        artifact_type=artifact_record.artifact_type,
        content=artifact_record.content,
        is_evidence_grounded=artifact_record.is_evidence_grounded,
        created_at=artifact_record.created_at.isoformat(),
        metadata=artifact_record.artifact_metadata or {},
    )


def get_artifact_by_id(db: Session, artifact_id: str) -> Optional[ArtifactResponse]:
    artifact = db.query(Artifact).filter(Artifact.id == artifact_id).first()
    if not artifact:
        return None
    return ArtifactResponse(
        id=artifact.id,
        conversation_id=artifact.conversation_id,
        title=artifact.title,
        artifact_type=artifact.artifact_type,
        content=artifact.content,
        is_evidence_grounded=artifact.is_evidence_grounded,
        created_at=artifact.created_at.isoformat(),
        metadata=artifact.artifact_metadata or {},
    )
